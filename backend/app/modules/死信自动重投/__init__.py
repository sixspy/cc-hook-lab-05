NAME = "死信自动重投"
骨签 = BONE
挂上 = True


def 闸口(失败次数: int, 阈值: int = 3) -> dict:
    达阈 = int(失败次数) >= int(阈值)
    return {
        "骨签": BONE,
        "失败次数": int(失败次数),
        "阈值": int(阈值),
        "达阈": 达阈,
        "放行": 达阈,
        "闸口": (
            f"放行：失败{失败次数}/{阈值}次已达阈，同票抬回待投"
            if 达阈
            else f"拦截：失败{失败次数}/{阈值}次未达阈，留匣禁投"
        ),
    }
